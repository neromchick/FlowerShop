#!/bin/bash
# =================================================================
# Скрипт автоматического обновления и деплоя FlowerShop на сервере
# =================================================================
set -e

echo "==> [1/4] Проверка наличия файла .env..."
if [ ! -f .env ]; then
    echo "ОШИБКА: Файл .env не найден!"
    echo "Скопируйте .env.example в .env и укажите боевые пароли:"
    echo "  cp .env.example .env"
    echo "  nano .env"
    exit 1
fi

echo "==> [2/4] Подтягивание свежего кода из Git..."
git pull

echo "==> [3/4] Сборка и перезапуск Docker контейнеров..."
docker compose up -d --build

echo "==> [4/4] Очистка неиспользуемых старых образов Docker..."
docker image prune -f

echo ""
echo "================================================="
echo " Деплой успешно завершен!"
echo " Статус контейнеров:"
echo "================================================="
docker compose ps
